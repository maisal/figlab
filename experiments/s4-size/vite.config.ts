// Vite build of the S4 stand-in app: three pages (plain, Preact, React) and a
// Service Worker that precaches every file of the build (spec.md 13, Offline).

import { createHash } from "node:crypto";
import { defineConfig, type Plugin } from "vite";

function serviceWorker(): Plugin {
  return {
    name: "s4-service-worker",
    apply: "build",
    enforce: "post",
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith(".map"));
      for (const page of ["index.html", "preact.html", "react.html"]) {
        if (!files.includes(page)) files.push(page);
      }
      const list = ["./", ...files.sort()];
      const version = createHash("sha256").update(list.join("\n")).digest("hex").slice(0, 12);
      const source = `// Generated by vite.config.ts. Precaches the whole app, then serves it cache-first.
const FILES = ${JSON.stringify(list)};
const CACHE = "s4-${version}";
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (url.origin !== location.origin || e.request.method !== "GET") return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((r) => r || fetch(e.request)));
});
self.addEventListener("message", (e) => {
  caches.open(CACHE).then((c) => c.keys()).then((keys) => {
    if (keys.length >= FILES.length) e.source.postMessage("precached");
  });
});
`;
      this.emitFile({ type: "asset", fileName: "sw.js", source });
    },
  };
}

export default defineConfig({
  root: "app",
  base: "./",
  plugins: [serviceWorker()],
  build: {
    outDir: "../dist",
    emptyOutDir: true,
    target: "es2022",
    // Keep every asset as a file (fonts and wasm are never inlined).
    assetsInlineLimit: 0,
    reportCompressedSize: false,
    rollupOptions: {
      input: {
        index: "app/index.html",
        preact: "app/preact.html",
        react: "app/react.html",
      },
    },
  },
  worker: { format: "es" },
  server: { fs: { allow: [".."] } },
});
