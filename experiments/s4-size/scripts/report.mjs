// Turns results/sizes.json into Markdown tables (results/sizes.md).
//
// Usage: node scripts/report.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { kib } from "./lib.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const S = JSON.parse(readFileSync(join(root, "results", "sizes.json"), "utf8"));
const R = S.results;
const get = (id, profile = "release", opt = "Oz") => R.find((r) => r.id === id && r.profile === profile && r.opt === opt);
const out = [];
const p = (s = "") => out.push(s);
const row = (cells) => p(`| ${cells.join(" | ")} |`);

p(`# S4 size tables`);
p();
p(`Generated by scripts/report.mjs from results/sizes.json. ${S.rustc}, wasm-bindgen ${S.wasmBindgen}, ${S.wasmOpt}.`);
p(`Sizes in KiB (1024 bytes). "gz" is gzip -9, "br" is brotli quality 11. Unless noted: profile \`release\` (opt-level "z", LTO, codegen-units 1, panic abort) and wasm-opt -Oz.`);
p();

function table(title, ids, note) {
  p(`## ${title}`);
  p();
  if (note) {
    p(note);
    p();
  }
  row(["Variant", "Contents", "wasm raw", "wasm gz", "wasm br", "JS glue gz"]);
  row(["---", "---", "---:", "---:", "---:", "---:"]);
  for (const id of ids) {
    const r = get(id);
    if (!r) continue;
    row([`\`${id}\``, r.note, kib(r.wasm.raw), kib(r.wasm.gzip), kib(r.wasm.brotli), kib(r.js.gzip)]);
  }
  p();
}

table("Baseline: the fixed cost of one module", ["baseline", "baseline-alloc", "baseline-fmt", "png-encoder"]);
table("Compute worker", [
  "compute",
  "compute-rmpfit",
  "compute-nofit",
  "compute-deps",
  "compute-standin",
  "compute-csv",
  "compute-sjis",
  "compute-lm",
  "compute-rmpfit-only",
  "compute-empty",
  "compute-app",
]);
table("Render module", ["render-hr", "render-rb", "render-hr-only", "render-rb-only", "render-standin", "render-hr-app", "render-rb-app"]);
table("Language service", ["lang-tables", "lang-serde", "lang-raw", "lang-none", "lang-app"]);
table("Export modules (loaded later)", ["pdf-writer-skrifa", "pdf-krilla", "pdf-krilla-default", "pdf-writer", "pdf-writer-min", "png", "png-raster", "png-default"]);
table("One module for render and export", ["render-hr+pdfwriter+png", "render-rb+krilla+png", "render-hr+krilla+png", "render-rb+pdfwriter+png"]);

// What each part adds, by difference of gz sizes.
p(`## What each part adds (difference of gz sizes)`);
p();
row(["Part", "Computed as", "gz added"]);
row(["---", "---", "---:"]);
const diff = (a, b) => get(a).wasm.gzip - get(b).wasm.gzip;
const parts = [
  ["csv", "compute-csv - compute-empty"],
  ["encoding_rs (Shift_JIS)", "compute-sjis - compute-empty"],
  ["levenberg-marquardt + nalgebra", "compute-lm - compute-empty"],
  ["rmpfit", "compute-rmpfit-only - compute-empty"],
  ["interpreter stand-in", "compute-standin - compute-empty"],
  ["all compute libraries", "compute-deps - compute-empty"],
  ["rustybuzz + ttf-parser", "render-rb-only - baseline-fmt"],
  ["harfrust + skrifa", "render-hr-only - baseline-fmt"],
  ["layout + SVG stand-in", "render-standin - baseline-fmt"],
  ["PNG encoder (png crate) alone", "png-encoder - baseline-alloc"],
  ["tiny-skia rasterizer (no PNG encoder)", "png-raster - baseline-alloc"],
  ["PNG encoder on top of tiny-skia", "png - png-raster"],
  ["commands.json as raw text", "lang-raw - lang-none"],
  ["commands.json as Rust tables", "lang-tables - lang-none"],
  ["commands.json + serde_json", "lang-serde - lang-none"],
  ["allowance (generated code), compute", "compute-app - compute"],
  ["allowance (generated code), render (harfrust)", "render-hr-app - render-hr"],
  ["allowance (generated code), render (rustybuzz)", "render-rb-app - render-rb"],
  ["allowance (generated code), lang", "lang-app - lang-tables"],
];
for (const [name, expr] of parts) {
  const [a, b] = expr.split(" - ");
  if (!get(a) || !get(b)) continue;
  row([name, `\`${expr}\``, kib(diff(a, b))]);
}
p();

// Split versus combined.
p(`## Three modules or one`);
p();
row(["Render", "PDF", "Three modules: sum of gz", "One module: gz", "Duplicated in the split (gz)"]);
row(["---", "---", "---:", "---:", "---:"]);
for (const [r, pdf, comb] of [
  ["render-hr", "pdf-writer-skrifa", "render-hr+pdfwriter+png"],
  ["render-rb", "pdf-krilla", "render-rb+krilla+png"],
  ["render-hr", "pdf-krilla", "render-hr+krilla+png"],
  ["render-rb", "pdf-writer", "render-rb+pdfwriter+png"],
]) {
  if (!get(comb)) continue;
  const sum = get(r).wasm.gzip + get(pdf).wasm.gzip + get("png").wasm.gzip;
  row([`\`${r}\``, `\`${pdf}\``, kib(sum), kib(get(comb).wasm.gzip), kib(sum - get(comb).wasm.gzip)]);
}
p();

// Profiles and wasm-opt.
const mains = [...new Set(R.filter((r) => r.profile === "release-plain").map((r) => r.id))];
p(`## Compiler profile and wasm-opt (wasm gz)`);
p();
row(["Variant", "plain (O3, no LTO) + Oz", "O3 + LTO + Oz", "s + LTO + Oz", "z + LTO, no wasm-opt", "z + LTO + O3", "z + LTO + Os", "z + LTO + Oz", "z + LTO + Oz --converge", "nightly immediate-abort + Oz"]);
row(["---", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:"]);
for (const id of mains) {
  const c = (profile, opt) => {
    const r = get(id, profile, opt);
    return r ? kib(r.wasm.gzip) : "";
  };
  row([
    `\`${id}\``,
    c("release-plain", "Oz"),
    c("release-o3", "Oz"),
    c("release-s", "Oz"),
    c("release", "none"),
    c("release", "O3"),
    c("release", "Os"),
    c("release", "Oz"),
    c("release", "Oz-converge"),
    c("nightly-immediate-abort", "Oz"),
  ]);
}
p();
p(`Raw sizes of the same builds:`);
p();
row(["Variant", "plain + Oz", "O3 + LTO + Oz", "s + LTO + Oz", "z, no wasm-opt", "z + O3", "z + Os", "z + Oz", "z + Oz --converge", "nightly + Oz"]);
row(["---", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:"]);
for (const id of mains) {
  const c = (profile, opt) => {
    const r = get(id, profile, opt);
    return r ? kib(r.wasm.raw) : "";
  };
  row([
    `\`${id}\``,
    c("release-plain", "Oz"),
    c("release-o3", "Oz"),
    c("release-s", "Oz"),
    c("release", "none"),
    c("release", "O3"),
    c("release", "Os"),
    c("release", "Oz"),
    c("release", "Oz-converge"),
    c("nightly-immediate-abort", "Oz"),
  ]);
}
p();

// Attribution.
p(`## What dominates (code bytes by crate, raw, after -Oz)`);
p();
p(`From the name section of a -Oz build made with \`wasm-opt -g\` (scripts/attribute.mjs). Code that was inlined is counted for the function it was inlined into, so this is approximate. "(data)" is the data section (tables, strings).`);
p();
for (const id of [...mains, "lang-serde", "pdf-writer-min", "compute-app", "render-hr-app"]) {
  const r = R.find((x) => x.id === id && x.profile === "release" && x.crates);
  if (!r) continue;
  const total = Object.values(r.crates).reduce((a, b) => a + b, 0);
  const top = Object.entries(r.crates)
    .slice(0, 8)
    .map(([k, v]) => `${k} ${kib(v)} (${((100 * v) / total).toFixed(0)}%)`)
    .join(", ");
  p(`- \`${id}\` (${kib(total)} KiB): ${top}`);
}
p();

writeFileSync(join(root, "results", "sizes.md"), out.join("\n"));
console.log(out.join("\n"));
